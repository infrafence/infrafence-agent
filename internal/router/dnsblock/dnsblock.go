// Package dnsblock blocks malicious domains through dnsmasq: a generated
// file of local=/domain/ lines (NXDOMAIN for the domain and its
// subdomains, nothing asked upstream) in each dnsmasq instance's conf-dir.
// The list lives in tmpfs (never on flash) and is linked into the conf-dir
// only in Full protection; in Learning mode it is only used to recognise
// lookups of listed domains.
package dnsblock

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"sync"
	"time"
)

// FileName is the file the agent puts in dnsmasq's conf-dir.
const FileName = "infrafence-block.conf"

// Canary answered NXDOMAIN in Full protection: Firefox then keeps its DNS
// lookups on the router instead of its own DNS-over-HTTPS.
const canary = "use-application-dns.net"

// Blocker owns the list file and its links into dnsmasq's conf-dirs.
type Blocker struct {
	// StateDir holds the list (tmpfs: /tmp/infrafence).
	StateDir string
	// ConfDirs finds dnsmasq's conf-dirs; Restart restarts dnsmasq.
	ConfDirs func() []string
	Restart  func() error
	Now      func() time.Time
	// MinRestart is the shortest time between two dnsmasq restarts.
	MinRestart time.Duration
	// Protected names are never blocked (the dashboard, the package feed),
	// nor any of their parents.
	Protected []string
	// Probe checks dnsmasq answers after a restart (with the list in force,
	// that the canary is NXDOMAIN); replaced in tests.
	Probe func(blocked bool) error

	mu          sync.Mutex
	index       *Index
	count       int
	dropped     int
	full        bool
	linked      bool // the list is linked into the conf-dirs
	dirty       bool // dnsmasq must be restarted to see the change
	broken      bool // dnsmasq failed with this list: not linked again until a new one
	lastRestart time.Time
}

// ErrUnhealthy: dnsmasq did not answer after loading the list, which was
// taken out again.
var ErrUnhealthy = errors.New("dnsmasq did not answer with the list: list removed, DNS restored")

func New(stateDir string) *Blocker {
	return &Blocker{
		StateDir:   stateDir,
		ConfDirs:   ConfDirs,
		Restart:    restartDnsmasq,
		Probe:      probeDnsmasq,
		Now:        time.Now,
		MinRestart: 5 * time.Minute,
		// The first Apply removes a list left by an earlier run.
		dirty: true,
	}
}

func (b *Blocker) listPath() string { return filepath.Join(b.StateDir, "block.conf") }

// catPath lists the domains whose category is not "malware" ("domain cat"
// lines), so a restarted agent can rebuild the index from the files.
func (b *Blocker) catPath() string { return filepath.Join(b.StateDir, "block.cat") }

// Index is the list loaded (nil before the first load).
func (b *Blocker) Index() *Index {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.index
}

// Count is the number of domains loaded and how many the cap left out.
func (b *Blocker) Count() (int, int) {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.count, b.dropped
}

// Available says whether dnsmasq is there to enforce the list.
func Available() bool {
	_, err := os.Stat("/etc/init.d/dnsmasq")
	return err == nil
}

// ErrTooFew: the list had fewer valid domains than announced (or none),
// e.g. a captive portal's page instead of the list. The old list stays.
var ErrTooFew = errors.New("domain list has too few valid domains")

// Load reads a list ("domain [category]" per line, # comments) from r,
// keeping at most max domains, and replaces the current one. Invalid lines
// are skipped; with fewer than min valid domains (or none) the current
// list stays. The file is written to a temporary name and renamed, so
// dnsmasq never reads half a list.
func (b *Blocker) Load(r io.Reader, max, min int, allowEmpty bool) (int, error) {
	if err := os.MkdirAll(b.StateDir, 0o700); err != nil {
		return 0, err
	}
	tmp, err := os.CreateTemp(b.StateDir, ".block-*.tmp")
	if err != nil {
		return 0, err
	}
	defer os.Remove(tmp.Name())
	w := bufio.NewWriterSize(tmp, 64<<10)
	var cats strings.Builder
	fmt.Fprintf(w, "# InfraFence blocked domains, generated by infrafence-router: do not edit\nlocal=/%s/\n", canary)
	var ib indexBuilder
	seen := 0
	dropped := 0
	br := bufio.NewReaderSize(r, 4096)
	var readErr error
	for {
		raw, err := br.ReadSlice('\n')
		if err == bufio.ErrBufferFull {
			// A line longer than any domain: skip the rest of it.
			for err == bufio.ErrBufferFull {
				_, err = br.ReadSlice('\n')
			}
			if err != nil && err != io.EOF {
				readErr = err
				break
			}
			if err == io.EOF {
				break
			}
			continue
		}
		if err != nil && err != io.EOF {
			readErr = err
			break
		}
		eof := err == io.EOF
		line := strings.TrimSpace(string(raw))
		if line == "" || line[0] == '#' {
			if eof {
				break
			}
			continue
		}
		fs := strings.Fields(line)
		d := strings.TrimSuffix(strings.ToLower(fs[0]), ".")
		if !ValidDomain(d) || b.protected(d) || neverBlock(d) {
			if eof {
				break
			}
			continue
		}
		cat := CatMalware
		if len(fs) > 1 {
			cat = parseCategory(fs[1])
		}
		if max > 0 && seen >= max {
			dropped++
			if eof {
				break
			}
			continue
		}
		seen++
		ib.add(d, cat)
		fmt.Fprintf(w, "local=/%s/\n", d)
		if cat != CatMalware && cats.Len() < 4<<20 {
			cats.WriteString(d + " " + cat.String() + "\n")
		}
		if eof {
			break
		}
	}
	if readErr != nil {
		tmp.Close()
		return 0, fmt.Errorf("read list: %w", readErr)
	}
	if seen == 0 && !allowEmpty || seen < min {
		tmp.Close()
		return seen, fmt.Errorf("%w: %d (expected %d)", ErrTooFew, seen, min)
	}
	if err := w.Flush(); err != nil {
		tmp.Close()
		return 0, err
	}
	if err := tmp.Close(); err != nil {
		return 0, err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return 0, err
	}
	if err := writeAtomic(b.catPath(), []byte(cats.String())); err != nil {
		return 0, err
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	if err := os.Rename(tmp.Name(), b.listPath()); err != nil {
		return 0, err
	}
	b.index = ib.build()
	b.count = b.index.Len()
	b.dropped = dropped
	b.broken = false
	// The links point at the old file's inode: link the new one.
	if b.linked {
		b.linked = false
		b.dirty = true
	}
	return b.count, nil
}

// Adopt takes over the list a previous run of the agent left in tmpfs
// (and its links into dnsmasq's conf-dirs, if they are there), so a
// restarted agent neither re-downloads it nor restarts dnsmasq. It returns
// false when there is no list to adopt.
func (b *Blocker) Adopt() bool {
	f, err := os.Open(b.listPath())
	if err != nil {
		return false
	}
	defer f.Close()
	var ib indexBuilder
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 4096), 4096)
	for sc.Scan() {
		l := sc.Text()
		if !strings.HasPrefix(l, "local=/") || !strings.HasSuffix(l, "/") {
			continue
		}
		d := strings.TrimSuffix(strings.TrimPrefix(l, "local=/"), "/")
		if d != canary && ValidDomain(d) && !b.protected(d) && !neverBlock(d) {
			ib.add(d, CatMalware)
		}
	}
	if sc.Err() != nil {
		return false
	}
	if cf, err := os.Open(b.catPath()); err == nil {
		cs := bufio.NewScanner(cf)
		for cs.Scan() {
			if fs := strings.Fields(cs.Text()); len(fs) == 2 && ValidDomain(fs[0]) {
				ib.add(fs[0], parseCategory(fs[1]))
			}
		}
		cf.Close()
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	b.index = ib.build()
	b.count = b.index.Len()
	b.linked = b.linksPresent()
	b.full = b.linked
	b.dirty = false
	return b.count > 0
}

func writeAtomic(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

func (b *Blocker) protected(d string) bool {
	for _, p := range b.Protected {
		p = strings.ToLower(strings.TrimSuffix(p, "."))
		if p == "" {
			continue
		}
		// d is p, a parent of p (blocking it blocks p), or a child of p.
		if d == p || strings.HasSuffix(p, "."+d) || strings.HasSuffix(d, "."+p) {
			return true
		}
	}
	return false
}

// SetFull turns enforcement on (link the list, restart dnsmasq) or off.
func (b *Blocker) SetFull(full bool) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.full != full {
		b.full = full
		b.dirty = true
	}
}

// Apply brings dnsmasq's conf-dirs to the wanted state and restarts it
// when needed, at most once per MinRestart (except the first time). It
// returns whether the list is in force.
func (b *Blocker) Apply() (bool, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	wantLinked := b.full && b.index.Len() > 0 && !b.broken
	// Someone else restarted dnsmasq, or the conf-dir was recreated: check
	// the links are really there.
	if b.linked && wantLinked && !b.linksPresent() {
		b.linked = false
		b.dirty = true
	}
	if !b.dirty && b.linked == wantLinked {
		return b.linked, nil
	}
	now := b.Now()
	if !b.lastRestart.IsZero() && now.Sub(b.lastRestart) < b.MinRestart {
		return b.linked, nil // later
	}
	var errs []error
	changed := false
	dirs := b.ConfDirs()
	if wantLinked && len(dirs) == 0 {
		errs = append(errs, errors.New("no dnsmasq conf-dir found (is dnsmasq running?)"))
	}
	for _, dir := range dirs {
		dst := filepath.Join(dir, FileName)
		_, statErr := os.Lstat(dst)
		if statErr == nil {
			if err := os.Remove(dst); err != nil {
				errs = append(errs, err)
				continue
			}
			changed = true
		}
		if wantLinked {
			if err := linkOrCopy(b.listPath(), dst); err != nil {
				errs = append(errs, err)
				continue
			}
			changed = true
		}
	}
	b.dirty = false
	b.linked = wantLinked && len(errs) == 0 && len(dirs) > 0
	if changed {
		b.lastRestart = now
		if err := b.Restart(); err != nil {
			errs = append(errs, err)
		}
		if err := b.Probe(b.linked); err != nil && b.linked {
			// The household must never lose DNS over the list: take it
			// out, restart, and keep it out until a new list arrives.
			log.Printf("[dns] dnsmasq unhealthy with the list (%v): removing it", err)
			for _, dir := range dirs {
				_ = os.Remove(filepath.Join(dir, FileName))
			}
			_ = b.Restart()
			b.linked, b.broken = false, true
			errs = append(errs, ErrUnhealthy)
		}
	}
	return b.linked, errors.Join(errs...)
}

func (b *Blocker) linksPresent() bool {
	src, err := os.Stat(b.listPath())
	if err != nil {
		return false
	}
	dirs := b.ConfDirs()
	if len(dirs) == 0 {
		return false
	}
	for _, dir := range dirs {
		st, err := os.Stat(filepath.Join(dir, FileName))
		if err != nil || st.Size() != src.Size() {
			return false
		}
	}
	return true
}

// Clear drops the list (the dashboard no longer sends one): it leaves the
// conf-dirs at the next Apply.
func (b *Blocker) Clear() error {
	b.mu.Lock()
	defer b.mu.Unlock()
	b.index, b.count, b.dropped = nil, 0, 0
	b.dirty = true
	if err := os.Remove(b.catPath()); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

// Remove takes the list out of every conf-dir and deletes it (uninstall).
func (b *Blocker) Remove() error {
	b.mu.Lock()
	defer b.mu.Unlock()
	removed := false
	for _, dir := range b.ConfDirs() {
		if err := os.Remove(filepath.Join(dir, FileName)); err == nil {
			removed = true
		}
	}
	_ = os.Remove(b.listPath())
	_ = os.Remove(b.catPath())
	b.linked, b.full, b.index, b.count = false, false, nil, 0
	if removed {
		return b.Restart()
	}
	return nil
}

// linkOrCopy hard-links (same tmpfs: no extra RAM) or copies.
func linkOrCopy(src, dst string) error {
	if err := os.Link(src, dst); err == nil {
		return nil
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	tmp := dst + ".tmp~" // dnsmasq skips names ending in ~
	out, err := os.OpenFile(tmp, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o644)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		os.Remove(tmp)
		return err
	}
	if err := out.Close(); err != nil {
		os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, dst)
}

// ConfDirs reads the conf-dir of every dnsmasq instance from the
// configuration the init script generates (/var/etc/dnsmasq.conf.<id>);
// OpenWrt 21.02 and older use /tmp/dnsmasq.d.
func ConfDirs() []string {
	files, _ := filepath.Glob("/var/etc/dnsmasq.conf.*")
	var dirs []string
	seen := map[string]bool{}
	for _, f := range files {
		for _, d := range confDirsIn(f) {
			if !seen[d] {
				seen[d] = true
				dirs = append(dirs, d)
			}
		}
	}
	if len(dirs) == 0 {
		if st, err := os.Stat("/tmp/dnsmasq.d"); err == nil && st.IsDir() {
			dirs = append(dirs, "/tmp/dnsmasq.d")
		}
	}
	return dirs
}

func confDirsIn(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		return nil
	}
	defer f.Close()
	var out []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		l := strings.TrimSpace(sc.Text())
		if !strings.HasPrefix(l, "conf-dir=") {
			continue
		}
		d, _, _ := strings.Cut(strings.TrimPrefix(l, "conf-dir="), ",")
		d = filepath.Clean(d)
		// Only tmpfs directories: the agent never writes to flash or
		// elsewhere on the user's say-so.
		if strings.HasPrefix(d, "/tmp/") || strings.HasPrefix(d, "/var/") {
			if st, err := os.Stat(d); err == nil && st.IsDir() {
				out = append(out, d)
			}
		}
	}
	return out
}

// Shared platforms whose own domain (or a parent of it) is never blocked:
// listing "github.io" would block every site on it. Their subdomains
// ("evil.github.io") can be listed.
var shared = []string{
	"amazonaws.com", "cloudfront.net", "azureedge.net", "azurewebsites.net", "windows.net", "akamaized.net", "akamaiedge.net",
	"akamai.net", "edgekey.net", "fastly.net", "cloudflare.com", "cloudflare.net", "workers.dev", "pages.dev",
	"github.io", "githubusercontent.com", "github.com", "gitlab.io", "googleusercontent.com", "googleapis.com", "gstatic.com",
	"google.com", "apple.com", "icloud.com", "microsoft.com", "live.com", "office.com", "facebook.com", "fbcdn.net",
	"whatsapp.net", "netlify.app", "vercel.app", "herokuapp.com", "firebaseapp.com", "web.app", "blogspot.com",
	"wordpress.com", "dropbox.com", "drive.google.com", "duckdns.org", "no-ip.com", "ddns.net",
}

func neverBlock(d string) bool {
	for _, s := range shared {
		if d == s || strings.HasSuffix(s, "."+d) {
			return true
		}
	}
	return false
}

// probeDnsmasq asks dnsmasq (127.0.0.1:53) for the canary: NXDOMAIN when
// the list is in force, any answer otherwise. It retries for 15 s (dnsmasq
// takes a moment to load a large list on a slow router).
func probeDnsmasq(blocked bool) error {
	deadline := time.Now().Add(15 * time.Second)
	var last error
	for time.Now().Before(deadline) {
		nx, err := queryLocal(canary)
		switch {
		case err != nil:
			last = err
		case blocked && !nx:
			last = errors.New("the canary is not blocked")
		default:
			return nil
		}
		time.Sleep(time.Second)
	}
	return last
}

func restartDnsmasq() error {
	// restart, not reload: SIGHUP does not re-read conf-dir.
	out, err := exec.Command("/etc/init.d/dnsmasq", "restart").CombinedOutput()
	if err != nil {
		return fmt.Errorf("dnsmasq restart: %v: %s", err, strings.TrimSpace(string(out)))
	}
	log.Printf("[dns] dnsmasq restarted")
	return nil
}

// ValidDomain accepts host names of two labels or more, letters, digits,
// hyphens and underscores, and refuses public suffixes like "co.uk".
func ValidDomain(d string) bool {
	if len(d) < 4 || len(d) > 253 {
		return false
	}
	labels := strings.Split(d, ".")
	if len(labels) < 2 {
		return false
	}
	for _, l := range labels {
		if len(l) == 0 || len(l) > 63 || l[0] == '-' || l[len(l)-1] == '-' {
			return false
		}
		for i := 0; i < len(l); i++ {
			c := l[i]
			if !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-' || c == '_') {
				return false
			}
		}
	}
	tld := labels[len(labels)-1]
	if tld[0] >= '0' && tld[0] <= '9' {
		return false // an address, not a name
	}
	if len(labels) == 2 && len(tld) == 2 && publicSecond[labels[0]] {
		return false
	}
	return true
}

var publicSecond = map[string]bool{"co": true, "com": true, "net": true, "org": true, "gov": true, "ac": true, "edu": true, "or": true, "ne": true, "go": true}
