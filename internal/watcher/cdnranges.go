type cdnNet struct {
	net      *net.IPNet
	provider string
}

var (
	cdnNets     []cdnNet
	cdnNetsOnce sync.Once
)

// cdnProvider names the CDN whose edge ip is, "" when it is none. Linear
// over a few hundred networks: called once per address that crosses the
// http_flood threshold, never per request.
func cdnProvider(ip string) string {
	cdnNetsOnce.Do(func() {
		for _, r := range cdnRanges {
			for _, c := range r.cidrs {
				if _, n, err := net.ParseCIDR(c); err == nil {
					cdnNets = append(cdnNets, cdnNet{n, r.provider})
				} else if a := net.ParseIP(c); a != nil {
					bits := 128
					if v4 := a.To4(); v4 != nil {
						a, bits = v4, 32
					}
					cdnNets = append(cdnNets, cdnNet{&net.IPNet{IP: a, Mask: net.CIDRMask(bits, bits)}, r.provider})
				}
			}
		}
	})
	a := net.ParseIP(ip)
	if a == nil {
		return ""
	}
	for _, n := range cdnNets {
		if n.net.Contains(a) {
			return n.provider
		}
	}
	return ""
}
